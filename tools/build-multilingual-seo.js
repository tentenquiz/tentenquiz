function readJson(filePath) {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function loadBrowserGlobal(fileName, globalName) {
    const sandbox = { window: {}, console };
    sandbox.globalThis = sandbox.window;
    vm.createContext(sandbox);
    vm.runInContext(fs.readFileSync(path.join(projectRoot, fileName), 'utf8'), sandbox, { filename: fileName });
    const value = sandbox.window[globalName];
    if (!value) throw new Error(`${fileName} did not expose ${globalName}`);
    return value;
}

function normalizeBaseUrl(value) {
    return String(value || '').trim().replace(/\/+$/, '');
}

function escapeHtml(value) {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function escapeXml(value) {
    return escapeHtml(value);
}

function getAttribute(tag, name) {
    const escapedName = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const match = tag.match(new RegExp(`\\s${escapedName}\\s*=\\s*(["'])(.*?)\\1`, 'i'));
    return match ? match[2] : '';
}

function setAttribute(tag, name, value) {
    const escapedName = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const attributePattern = new RegExp(`\\s${escapedName}\\s*=\\s*(["']).*?\\1`, 'i');
    const serialized = ` ${name}="${escapeHtml(value)}"`;
    if (attributePattern.test(tag)) return tag.replace(attributePattern, serialized);
    return tag.replace(/\s*\/?\s*>$/, (ending) => `${serialized}${ending}`);
}

function replaceTitle(html, title) {
    return html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${escapeHtml(title)}</title>`);
}

function readTitle(html) {
    const match = html.match(/<title>([\s\S]*?)<\/title>/i);
    return match ? match[1].replace(/<[^>]+>/g, '').trim() : '';
}

function readMetaContent(html, attributeName, attributeValue) {
    let content = '';
    html.replace(/<meta\b[^>]*>/gi, (tag) => {
        if (getAttribute(tag, attributeName).toLowerCase() === attributeValue.toLowerCase()) {
            content = getAttribute(tag, 'content');
        }
        return tag;
    });
    return content;
}

function upsertMeta(html, attributeName, attributeValue, content) {
    let found = false;
    html = html.replace(/<meta\b[^>]*>/gi, (tag) => {
        if (getAttribute(tag, attributeName).toLowerCase() !== attributeValue.toLowerCase()) return tag;
        found = true;
        return setAttribute(tag, 'content', content);
    });
    if (found) return html;
    return html.replace('</head>', `    <meta ${attributeName}="${escapeHtml(attributeValue)}" content="${escapeHtml(content)}">\n</head>`);
}

function upsertCanonical(html, canonicalUrl) {
    let found = false;
    html = html.replace(/<link\b[^>]*>/gi, (tag) => {
        if (getAttribute(tag, 'rel').toLowerCase() !== 'canonical') return tag;
        found = true;
        return setAttribute(tag, 'href', canonicalUrl);
    });
    if (found) return html;
    return html.replace('</head>', `    <link rel="canonical" href="${escapeHtml(canonicalUrl)}">\n</head>`);
}

function ensureBaseHref(html) {
    html = html.replace(/\s*<base\b[^>]*>\s*/gi, '\n');
    return html.replace(/(<meta\s+charset=[^>]+>)/i, '$1\n    <base href="/">');
}

function setDocumentLanguage(html, locale) {
    return html.replace(/<html\b[^>]*>/i, (tag) => {
        let next = setAttribute(tag, 'lang', locale.htmlLang);
        next = setAttribute(next, 'dir', locale.dir);
        return next;
    });
}

function localizedPath(locale, pageKey) {
    return pageKey === 'home' ? `/${locale.slug}/` : `/${locale.slug}/${pageKey}/`;
}

function absoluteUrl(baseUrl, urlPath) {
    return `${baseUrl}${urlPath.startsWith('/') ? urlPath : `/${urlPath}`}`;
}

function buildAlternateLinks(baseUrl, locales, pageDefinition) {
    const languageLinks = locales.map((locale) => (
        `    <link rel="alternate" hreflang="${locale.hreflang}" href="${escapeHtml(absoluteUrl(baseUrl, localizedPath(locale, pageDefinition.key)))}" data-tenten-static-hreflang>`
    ));
    languageLinks.push(
        `    <link rel="alternate" hreflang="x-default" href="${escapeHtml(absoluteUrl(baseUrl, pageDefinition.legacyPath))}" data-tenten-static-hreflang>`
    );
    return languageLinks.join('\n');
}

function injectAlternateLinks(html, links) {
    html = html.replace(/\s*<link\b[^>]*>\s*/gi, (fullTag) => {
        const tag = fullTag.trim();
        return getAttribute(tag, 'rel').toLowerCase() === 'alternate' && getAttribute(tag, 'hreflang')
            ? '\n'
            : fullTag;
    });
    const canonicalPattern = /<link\b[^>]*>/gi;
    let injected = false;
    html = html.replace(canonicalPattern, (tag) => {
        if (injected || getAttribute(tag, 'rel').toLowerCase() !== 'canonical') return tag;
        injected = true;
        return `${tag}\n${links}`;
    });
    return injected ? html : html.replace('</head>', `${links}\n</head>`);
}

function injectStaticLocaleBootstrap(html, locale, localePathMap) {
    html = html.replace(/\s*<script\b[^>]*data-tenten-static-locale[^>]*>[\s\S]*?<\/script>\s*/gi, '\n');
    const serializedPaths = JSON.stringify(localePathMap).replace(/</g, '\\u003c');
    const bootstrap = `    <script data-tenten-static-locale>\n` +
        `        window.__TENTEN_STATIC_INTERFACE_LANGUAGE__ = ${JSON.stringify(locale.code)};\n` +
        `        window.__TENTEN_STATIC_LOCALE_PATHS__ = ${serializedPaths};\n` +
        `    </script>\n`;
    const firstRuntimeScript = /(?=\s*<script\b[^>]*src=["'](?:global-config|content-translations)\.js)/i;
    return firstRuntimeScript.test(html)
        ? html.replace(firstRuntimeScript, `\n${bootstrap}`)
        : html.replace('</head>', `${bootstrap}</head>`);
}

function translateDataI18n(html, messages) {
    html = html.replace(
        /(<([a-z][\w:-]*)\b[^>]*\bdata-i18n=["']([^"']+)["'][^>]*>)([\s\S]*?)(<\/\2>)/gi,
        (match, opening, tagName, key, currentContent, closing) => (
            Object.prototype.hasOwnProperty.call(messages, key)
                ? `${opening}${escapeHtml(messages[key])}${closing}`
                : match
        )
    );

    html = html.replace(/<[a-z][^>]*\bdata-i18n-(?:aria|placeholder)=["'][^"']+["'][^>]*>/gi, (tag) => {
        let next = tag;
        const ariaKey = getAttribute(tag, 'data-i18n-aria');
        const placeholderKey = getAttribute(tag, 'data-i18n-placeholder');
        if (ariaKey && Object.prototype.hasOwnProperty.call(messages, ariaKey)) {
            next = setAttribute(next, 'aria-label', messages[ariaKey]);
            next = setAttribute(next, 'title', messages[ariaKey]);
        }
        if (placeholderKey && Object.prototype.hasOwnProperty.call(messages, placeholderKey)) {
            next = setAttribute(next, 'placeholder', messages[placeholderKey]);
        }
        return next;
    });
    return html;
}

function renderTranslatedArticle(html, pageKey, page) {
    const headingId = headingIds[pageKey];
    const articleContent = `
            <header>
                <h1 id="${headingId}">${escapeHtml(page.title)}</h1>
                <p class="legal-effective-date">${escapeHtml(page.kicker)}</p>
            </header>
            <p class="legal-intro">${escapeHtml(page.intro)}</p>
            ${page.sections.map((section) => `
            <section>
                <h2>${escapeHtml(section.title)}</h2>
                ${section.html}
            </section>`).join('\n')}
        `;
    const articlePattern = new RegExp(`(<article\\b[^>]*\\bdata-content-page=["']${pageKey}["'][^>]*>)[\\s\\S]*?<\\/article>`, 'i');
    if (!articlePattern.test(html)) throw new Error(`Could not find ${pageKey} article in its template`);
    return html.replace(articlePattern, `$1${articleContent}</article>`);
}

function localizeContentChrome(html, common, currentPageKey) {
    html = html.replace(/<a\b[^>]*class=["'][^"']*legal-home-link[^"']*["'][^>]*>[\s\S]*?<\/a>/i, (anchor) => (
        anchor.replace(/>[^<]*<\/a>$/, `>${escapeHtml(common.backToQuiz)}</a>`)
    ));
    html = html.replace(/<a\b[^>]*class=["'][^"']*legal-brand[^"']*["'][^>]*>/i, (tag) => (
        setAttribute(tag, 'aria-label', common.brandHomeLabel)
    ));
    html = html.replace(/(<nav\b[^>]*class=["'][^"']*legal-footer-nav[^"']*["'][^>]*>)([\s\S]*?)(<\/nav>)/i, (match, opening, body, closing) => {
        let nextOpening = setAttribute(opening, 'aria-label', common.navigationLabel);
        let nextBody = body.replace(/<a\b[^>]*href=["']([^"']+)["'][^>]*>[\s\S]*?<\/a>/gi, (anchor, href) => {
            const fileName = href.split(/[?#]/)[0].split('/').pop();
            const pageKey = fileName === 'index.html' ? 'home' : fileName.replace(/\.html$/i, '');
            return common[pageKey]
                ? anchor.replace(/>[\s\S]*<\/a>$/, `>${escapeHtml(common[pageKey])}</a>`)
                : anchor;
        });
        nextBody = nextBody.replace(/<strong\b([^>]*)aria-current=["']page["']([^>]*)>[\s\S]*?<\/strong>/i, (strong) => (
            strong.replace(/>[\s\S]*<\/strong>$/, `>${escapeHtml(common[currentPageKey])}</strong>`)
        ));
        nextBody = nextBody.replace(/(<button\b[^>]*data-google-privacy-settings[^>]*>)[\s\S]*?(<\/button>)/i, `$1${escapeHtml(common.privacyCookieSettings)}$2`);
        return `${nextOpening}${nextBody}${closing}`;
    });
    return html;
}

function rewriteLocalizedLinks(html, locale) {
    const knownPages = new Set(['index.html', 'about.html', 'guide.html', 'contact.html', 'privacy.html', 'terms.html']);
    return html.replace(/<a\b[^>]*href=["'][^"']+["'][^>]*>/gi, (tag) => {
        const href = getAttribute(tag, 'href');
        if (!href || /^(?:https?:|mailto:|tel:|data:|#)/i.test(href)) return tag;
        const cleanPath = href.split(/[?#]/)[0].replace(/^\.\//, '');
        const fileName = cleanPath.split('/').pop();
        if (!knownPages.has(fileName)) return tag;
        const pageKey = fileName === 'index.html' ? 'home' : fileName.replace(/\.html$/i, '');
        return setAttribute(tag, 'href', localizedPath(locale, pageKey));
    });
}

function injectStructuredData(html, baseUrl, locale, title, description) {
    html = html.replace(/\s*<script\b[^>]*data-tenten-generated-schema[^>]*>[\s\S]*?<\/script>\s*/gi, '\n');
    const schema = {
        '@context': 'https://schema.org',
        '@type': 'SoftwareApplication',
        name: 'TentenQuiz',
        url: absoluteUrl(baseUrl, localizedPath(locale, 'home')),
        applicationCategory: 'EducationalApplication',
        operatingSystem: 'Web browser',
        inLanguage: locale.htmlLang,
        description,
        offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' }
    };
    const serialized = JSON.stringify(schema).replace(/</g, '\\u003c');
    return html.replace('</head>', `    <script type="application/ld+json" data-tenten-generated-schema>${serialized}</script>\n</head>`);
}

// ---------- Google AdSense ----------
// locales/site.json 의 adsenseClient (또는 환경변수 TENTEN_ADSENSE_CLIENT) 에
// 'ca-pub-...' 형식의 게시자 ID 를 넣으면 72개 페이지 전부에 로더가 주입됩니다.
// 비어 있으면 아무것도 주입하지 않습니다(심사 전에는 비워두세요).
function normalizeAdsenseClient(value) {
    const client = String(value || '').trim();
    if (!client) return '';
    if (!/^ca-pub-\d{10,}$/.test(client)) {
        throw new Error(`Invalid AdSense publisher ID: ${client} (expected ca-pub-<digits>)`);
    }
    return client;
}

function injectAdsense(html, adsenseClient) {
    // 재실행 시 중복 주입을 막기 위해 기존 태그를 먼저 제거합니다.
    html = html.replace(/\s*<script\b[^>]*data-tenten-adsense[^>]*>[\s\S]*?<\/script>\s*/gi, '\n');
    html = html.replace(/\s*<meta\b[^>]*name=["']google-adsense-account["'][^>]*>\s*/gi, '\n');
    if (!adsenseClient) return html;

    const tags = `    <meta name="google-adsense-account" content="${escapeHtml(adsenseClient)}">\n`
        + `    <script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=${encodeURIComponent(adsenseClient)}"\n`
        + `            crossorigin="anonymous" data-tenten-adsense></script>\n`;
    return html.replace('</head>', `${tags}</head>`);
}

// ---------- head 스크립트: defer 금지 ----------
// 한 번 defer 를 넣었다가 앱을 깨뜨렸습니다. 기록으로 남깁니다.
//
// index.html 의 인라인 스크립트가 파싱 중에 window.tentenT() 를 호출해
// sectionLabelMap 을 만듭니다. tentenT 는 i18n.js 가 정의합니다.
// i18n.js 에 defer 를 붙이면 i18n.js 는 문서 파싱이 끝난 뒤 실행되는데
// 인라인 스크립트는 파싱 중에 즉시 실행되므로 tentenT 가 undefined 가 되고,
// 인라인 블록 전체가 TypeError 로 죽어 loadQuizSectionsFromJson 이
// 정의되지 않습니다. 결과: "데이터를 불러오지 못했습니다".
//
// 외부 스크립트끼리의 순서는 defer 가 보존하지만, 인라인 스크립트와의
// 순서는 보존하지 않습니다. 이게 핵심입니다.
//
// 성능을 개선하려면 defer 가 아니라 인라인 스크립트를 먼저 걷어내야 합니다.
// (sectionLabelMap 을 loadQuizSectionsFromJson 안으로 옮겨 지연 평가)
const DEFERRABLE_HEAD_SCRIPTS = ['global-config.js', 'i18n.js', 'cloud-backup-config.js', 'db.js'];

// 이전 빌드가 남긴 defer 를 제거해 자가 복구합니다.
function deferHeadScripts(html) {
    return html.replace(/<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*><\/script>/gi, (tag, src) => {
        const fileName = String(src).split(/[?#]/)[0].split('/').pop();
        if (!DEFERRABLE_HEAD_SCRIPTS.includes(fileName)) return tag;
        return tag.replace(/\s+defer\b/gi, '');
    });
}

function addGeneratedMarker(html) {
    if (html.includes(generatedMarker)) return html;
    return html.replace(/<!doctype html>/i, (doctype) => `${doctype}\n${generatedMarker}`);
}

function writeGeneratedHtml(filePath, html) {
    if (fs.existsSync(filePath)) {
        const current = fs.readFileSync(filePath, 'utf8');
        if (!current.includes(generatedMarker)) {
            throw new Error(`Refusing to overwrite a non-generated file: ${path.relative(projectRoot, filePath)}`);
        }
    }
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, addGeneratedMarker(html), 'utf8');
}

function getOutputPath(locale, pageKey) {
    return pageKey === 'home'
        ? path.join(projectRoot, locale.slug, 'index.html')
        : path.join(projectRoot, locale.slug, pageKey, 'index.html');
}

function applySocialTags(html, baseUrl, locale, title, description) {
    const imageUrl = absoluteUrl(baseUrl, resolveSocialImagePath(locale));
    html = upsertMeta(html, 'property', 'og:image', imageUrl);
    html = upsertMeta(html, 'property', 'og:image:secure_url', imageUrl);
    html = upsertMeta(html, 'property', 'og:image:width', SOCIAL_IMAGE_WIDTH);
    html = upsertMeta(html, 'property', 'og:image:height', SOCIAL_IMAGE_HEIGHT);
    html = upsertMeta(html, 'property', 'og:image:type', 'image/png');
    html = upsertMeta(html, 'property', 'og:image:alt', title);
    html = upsertMeta(html, 'name', 'twitter:card', 'summary_large_image');
    html = upsertMeta(html, 'name', 'twitter:title', title);
    html = upsertMeta(html, 'name', 'twitter:description', description);
    html = upsertMeta(html, 'name', 'twitter:image', imageUrl);
    return html;
}

function buildLocalizedPage({ sourceHtml, locale, pageDefinition, baseUrl, locales, localePathMap, uiMessages, contentTranslations, adsenseClient }) {
    const isHome = pageDefinition.key === 'home';
    const page = isHome ? null : contentTranslations.pages[locale.code]?.[pageDefinition.key];
    const title = isHome ? locale.homeTitle : (page?.metaTitle || readTitle(sourceHtml));
    const description = isHome
        ? locale.homeDescription
        : (page?.description || readMetaContent(sourceHtml, 'name', 'description'));
    const canonicalUrl = absoluteUrl(baseUrl, localizedPath(locale, pageDefinition.key));

    let html = sourceHtml;
    html = setDocumentLanguage(html, locale);
    html = ensureBaseHref(html);
    html = replaceTitle(html, title);
    html = upsertMeta(html, 'name', 'description', description);
    html = upsertMeta(html, 'property', 'og:title', title);
    html = upsertMeta(html, 'property', 'og:description', description);
    html = upsertMeta(html, 'property', 'og:locale', locale.ogLocale);
    html = upsertMeta(html, 'property', 'og:url', canonicalUrl);
    html = applySocialTags(html, baseUrl, locale, title, description);
    html = upsertCanonical(html, canonicalUrl);
    html = injectAlternateLinks(html, buildAlternateLinks(baseUrl, locales, pageDefinition));
    html = injectStaticLocaleBootstrap(html, locale, localePathMap);
    html = injectAdsense(html, adsenseClient);
    html = deferHeadScripts(html);

    if (isHome) {
        html = translateDataI18n(html, uiMessages[locale.code]);
        html = injectStructuredData(html, baseUrl, locale, title, description);
    } else {
        if (page) html = renderTranslatedArticle(html, pageDefinition.key, page);
        html = localizeContentChrome(html, contentTranslations.common[locale.code], pageDefinition.key);
    }

    return rewriteLocalizedLinks(html, locale);
}

function newestSourceDate(inputPaths) {
    // 이 빌드는 updateLegacySourceAlternates 로 소스 HTML 을 직접 수정합니다.
    // 그래서 mtime 을 기준으로 삼으면 내용이 하나도 안 바뀌어도 lastmod 가
    // 매번 "오늘"이 되고, 결국 구글이 이 사이트의 lastmod 신호를 무시하게 됩니다.
    // 마지막으로 "내용"이 바뀐 시점, 즉 해당 파일들을 건드린 마지막 커밋 날짜를 씁니다.
    // (커밋되지 않은 작업본은 반영되지 않습니다 — Git 연동 배포에서는 이게 맞습니다.)
    const relativePaths = inputPaths.map((filePath) => path.relative(projectRoot, filePath));
    try {
        const output = execFileSync('git', ['log', '-1', '--format=%cs', '--', ...relativePaths], {
            cwd: projectRoot,
            encoding: 'utf8'
        }).trim();
        if (/^\d{4}-\d{2}-\d{2}$/.test(output)) return output;
    } catch (_error) {
        // git 을 쓸 수 없으면 아래 mtime 폴백을 사용합니다.
    }
    const newest = Math.max(...inputPaths.map((filePath) => fs.statSync(filePath).mtimeMs));
    return new Date(newest).toISOString().slice(0, 10);
}

function buildSitemap(baseUrl, locales, lastModified) {
    const blocks = [];
    for (const pageDefinition of pageDefinitions) {
        const alternates = [
            ...locales.map((locale) => ({
                hreflang: locale.hreflang,
                url: absoluteUrl(baseUrl, localizedPath(locale, pageDefinition.key))
            })),
            { hreflang: 'x-default', url: absoluteUrl(baseUrl, pageDefinition.legacyPath) }
        ];
        const urls = [alternates[alternates.length - 1], ...alternates.slice(0, -1)];
        for (const entry of urls) {
            blocks.push([
                '    <url>',
                `        <loc>${escapeXml(entry.url)}</loc>`,
                `        <lastmod>${lastModified}</lastmod>`,
                ...alternates.map((alternate) => (
                    `        <xhtml:link rel="alternate" hreflang="${escapeXml(alternate.hreflang)}" href="${escapeXml(alternate.url)}" />`
                )),
                '    </url>'
            ].join('\n'));
        }
    }
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by tools/build-multilingual-seo.js. Do not edit directly. -->',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
        blocks.join('\n'),
        '</urlset>',
        ''
    ].join('\n');
}

// 루트(legacy) 페이지는 생성물이 아니라 소스 파일 자체입니다.
// x-default 타깃이자 `/` 에서 실제로 서빙되므로 소셜 태그와 애드센스가
// 여기에도 들어가야 합니다.
//
// 언어 정책:
//   /            → 영어. x-default 는 "어느 언어도 매칭되지 않은 방문자"용이고,
//                  12개 언어 글로벌 서비스의 기본값으로는 영어가 맞습니다.
//                  예전에는 <html lang="ko"> 인데 title·description·og:locale 은
//                  영어라 세 신호가 서로 어긋나 있었습니다.
//   /about.html 등 → 한국어 유지.
//                  content-translations.js 에 pages.ko 가 없어서 한국어 하위
//                  페이지(/ko/about/ 등)가 이 소스 파일의 본문을 그대로 씁니다.
//                  여기를 영어로 바꾸면 한국어 페이지가 통째로 영어가 됩니다.
//                  lang 속성만 실제 내용에 맞게 ko 로 명시합니다.
// 루트 페이지끼리의 내부 링크를 Pages 정식 URL 로 바꿉니다.
// about.html -> /about,  index.html -> /   (각각 308 왕복 1회를 없앱니다)
function rewriteLegacyLinks(html) {
    const map = new Map(pageDefinitions.map((page) => [page.sourceFile, page.legacyPath]));
    return html.replace(/<a\b[^>]*href=["'][^"']+["'][^>]*>/gi, (tag) => {
        const href = getAttribute(tag, 'href');
        if (!href || /^(?:https?:|mailto:|tel:|data:|#|\/)/i.test(href)) return tag;
        const cleanPath = href.split(/[?#]/)[0].replace(/^\.\//, '');
        if (cleanPath.includes('/') || !map.has(cleanPath)) return tag;
        return setAttribute(tag, 'href', map.get(cleanPath));
    });
}

function updateLegacySourceAlternates(baseUrl, locales, adsenseClient, uiMessages) {
    const englishLocale = locales.find((locale) => locale.code === 'en');
    const koreanLocale = locales.find((locale) => locale.code === 'ko');
    if (!englishLocale) throw new Error('The en locale is required for the root (x-default) page');

    let changed = 0;
    for (const pageDefinition of pageDefinitions) {
        const isHome = pageDefinition.key === 'home';
        const sourcePath = path.join(projectRoot, pageDefinition.sourceFile);
        const current = fs.readFileSync(sourcePath, 'utf8');

        const locale = isHome ? englishLocale : (koreanLocale || englishLocale);
        const title = isHome ? englishLocale.homeTitle : readTitle(current);
        const description = isHome
            ? englishLocale.homeDescription
            : readMetaContent(current, 'name', 'description');

        let next = setDocumentLanguage(current, locale);
        // 루트 페이지에도 <base href="/"> 가 필요합니다.
        // 서비스 워커가 오프라인 폴백으로 루트 셸을 /ko/ 같은 주소에서 내주면,
        // base 가 없을 때 style.css?v=... 가 /ko/style.css 로 해석되어
        // CSS·JS 를 하나도 못 찾고 무스타일 페이지가 나옵니다.
        next = ensureBaseHref(next);
        if (isHome) {
            next = replaceTitle(next, title);
            next = upsertMeta(next, 'name', 'description', description);
            next = upsertMeta(next, 'property', 'og:title', title);
            next = upsertMeta(next, 'property', 'og:description', description);
            // 본문의 data-i18n 요소를 영어로 채웁니다.
            // (런타임 i18n 이 어차피 덮어쓰지만, JS 를 실행하지 않는 크롤러와
            //  애드센스 심사자가 보는 초기 HTML 이 영어여야 합니다.)
            next = translateDataI18n(next, uiMessages[englishLocale.code]);
            next = injectStructuredData(next, baseUrl, englishLocale, title, description);
        }
        next = upsertMeta(next, 'property', 'og:locale', locale.ogLocale);
        next = injectAlternateLinks(next, buildAlternateLinks(baseUrl, locales, pageDefinition));
        next = upsertMeta(next, 'property', 'og:url', absoluteUrl(baseUrl, pageDefinition.legacyPath));
        // 소스에 하드코딩된 canonical(/about.html 등)이 308 대상을 가리키지 않도록 덮어씁니다.
        next = upsertCanonical(next, absoluteUrl(baseUrl, pageDefinition.legacyPath));
        next = rewriteLegacyLinks(next);
        next = applySocialTags(next, baseUrl, null, title, description);
        next = injectAdsense(next, adsenseClient);
        next = deferHeadScripts(next);
        next = next.replace(/^[\t ]+$/gm, '');
        if (next !== current) {
            fs.writeFileSync(sourcePath, next, 'utf8');
            changed += 1;
        }
    }
    return changed;
}

function main() {
    const siteConfigPath = path.join(localeRoot, 'site.json');
    const siteConfig = readJson(siteConfigPath);
    const baseUrl = normalizeBaseUrl(process.env.TENTEN_SITE_URL || siteConfig.baseUrl);
    if (!/^https:\/\//i.test(baseUrl)) throw new Error('The SEO base URL must use HTTPS');

    const adsenseClient = normalizeAdsenseClient(process.env.TENTEN_ADSENSE_CLIENT || siteConfig.adsenseClient);

    if (!fs.existsSync(path.join(projectRoot, DEFAULT_SOCIAL_IMAGE.replace(/^\//, '')))) {
        throw new Error(`소셜 공유 이미지가 없습니다: ${DEFAULT_SOCIAL_IMAGE} `
            + '(카카오톡은 og:image 가 없으면 미리보기를 아예 표시하지 않습니다)');
    }

    const locales = siteConfig.locales.map((slug) => readJson(path.join(localeRoot, slug, 'seo.json')));
    const codes = new Set();
    const slugs = new Set();
    for (const locale of locales) {
        if (!locale.code || !locale.slug || !locale.htmlLang || !locale.hreflang || !locale.homeTitle || !locale.homeDescription) {
            throw new Error(`Incomplete locale configuration: ${JSON.stringify(locale)}`);
        }
        if (codes.has(locale.code) || slugs.has(locale.slug)) throw new Error(`Duplicate locale code or slug: ${locale.code}`);
        codes.add(locale.code);
        slugs.add(locale.slug);
    }

    const uiMessages = loadBrowserGlobal('i18n.js', 'TENTEN_I18N_MESSAGES');
    const contentTranslations = loadBrowserGlobal('content-translations.js', 'TENTEN_CONTENT_TRANSLATIONS');
    const localePathMap = Object.fromEntries(locales.map((locale) => [locale.code, locale.slug]));

    for (const locale of locales) {
        if (!uiMessages[locale.code]) throw new Error(`Missing UI translations for ${locale.code}`);
        if (!contentTranslations.common[locale.code] || (locale.code !== 'ko' && !contentTranslations.pages[locale.code])) {
            throw new Error(`Missing content translations for ${locale.code}`);
        }
        if (uiMessages[locale.code].metaTitle !== locale.homeTitle || uiMessages[locale.code].metaDescription !== locale.homeDescription) {
            throw new Error(`SEO copy differs between i18n.js and locales/${locale.slug}/seo.json`);
        }
        for (const pageDefinition of pageDefinitions.filter((item) => item.key !== 'home' && locale.code !== 'ko')) {
            if (!contentTranslations.pages[locale.code][pageDefinition.key]) {
                throw new Error(`Missing ${pageDefinition.key} translation for ${locale.code}`);
            }
        }
    }

    updateLegacySourceAlternates(baseUrl, locales, adsenseClient, uiMessages);

    let generatedCount = 0;
    for (const locale of locales) {
        for (const pageDefinition of pageDefinitions) {
            const sourceHtml = fs.readFileSync(path.join(projectRoot, pageDefinition.sourceFile), 'utf8');
            const localizedHtml = buildLocalizedPage({
                sourceHtml,
                locale,
                pageDefinition,
                baseUrl,
                locales,
                localePathMap,
                uiMessages,
                contentTranslations,
                adsenseClient
            });
            writeGeneratedHtml(getOutputPath(locale, pageDefinition.key), localizedHtml);
            generatedCount += 1;
        }
    }

    const inputPaths = [
        siteConfigPath,
        path.join(projectRoot, 'i18n.js'),
        path.join(projectRoot, 'content-translations.js'),
        ...pageDefinitions.map((pageDefinition) => path.join(projectRoot, pageDefinition.sourceFile)),
        ...locales.map((locale) => path.join(localeRoot, locale.slug, 'seo.json'))
    ];
    const lastModified = newestSourceDate(inputPaths);
    const sitemap = buildSitemap(baseUrl, locales, lastModified);
    fs.writeFileSync(path.join(projectRoot, 'sitemap.xml'), sitemap, 'utf8');

    // robots.txt 의 Sitemap URL 이 하드코딩되어 있으면 TENTEN_SITE_URL 로 빌드했을 때
    // 실제 도메인과 어긋납니다. 여기서 baseUrl 기준으로 동기화합니다.
    const robotsPath = path.join(projectRoot, 'robots.txt');
    const robots = fs.readFileSync(robotsPath, 'utf8');
    const nextRobots = /^Sitemap:/mi.test(robots)
        ? robots.replace(/^Sitemap:.*$/mi, `Sitemap: ${absoluteUrl(baseUrl, '/sitemap.xml')}`)
        : `${robots.replace(/\s*$/, '')}\n\nSitemap: ${absoluteUrl(baseUrl, '/sitemap.xml')}\n`;
    if (nextRobots !== robots) fs.writeFileSync(robotsPath, nextRobots, 'utf8');

    console.log(`OK: generated ${generatedCount} localized static HTML pages`);
    console.log(`OK: generated sitemap.xml with ${pageDefinitions.length * (locales.length + 1)} canonical URLs (lastmod ${lastModified})`);
    console.log(`OK: base URL ${baseUrl}`);
    console.log(`OK: social image ${resolveSocialImagePath(null)}`);
    console.log(adsenseClient
        ? `OK: AdSense loader injected for ${adsenseClient}`
        : 'SKIP: AdSense 미설정 (locales/site.json 의 adsenseClient 또는 TENTEN_ADSENSE_CLIENT 를 채우면 주입됩니다)');
}

main();
